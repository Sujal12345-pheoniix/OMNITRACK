#!/usr/bin/env node
// Generates infra/staging.env with fresh random secrets. The file is git-ignored.
// Refuses to overwrite an existing file (rotating secrets is a deliberate operation).
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../infra/staging.env');
if (existsSync(target)) {
  console.log(`${target} already exists; not overwriting.`);
  process.exit(0);
}
const pw = () => randomBytes(24).toString('base64url');
writeFileSync(
  target,
  [
    '# Generated by scripts/make-staging-env.mjs. Never commit.',
    `POSTGRES_SUPERUSER_PASSWORD=${pw()}`,
    `OMNITRACK_MIGRATOR_PASSWORD=${pw()}`,
    `OMNITRACK_APP_PASSWORD=${pw()}`,
    `OMNITRACK_WORKER_PASSWORD=${pw()}`,
    `MFA_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
    '',
  ].join('\n'),
  { mode: 0o600 },
);
console.log(`Wrote ${target}`);
